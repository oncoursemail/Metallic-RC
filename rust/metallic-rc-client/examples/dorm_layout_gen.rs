//! Writes a Dorm layout that puts each 2026 Dorm prefab where the original Dorm scene has the same mesh.
//!
//! `cargo run --release -p metallic-rc-client --example dorm_layout_gen -- <scene.json> [game dir]`
//! `scene.json` is `unity-scene <...>/RecRoom_Data/level6 --json` run on an older build whose Dorm scene
//! (`dormroom2.unity`) is not scrambled. The Dorm's hull pieces (`Dorm_NN`, trims, mezzanine) are slices of the
//! scene's hull mesh in its frame, so they go where the hull object is; furniture goes where its mesh is.
//! Prefab placement P solves P * L = W, with L the mesh's transform inside the prefab and W its place in the scene.
use bevy::math::{Mat4, Quat, Vec3};
use metallic_rc_client::room::{self, Library};

fn unity_world(o: &serde_json::Value) -> Option<Mat4> {
    let f = |k: &str| -> Option<Vec<f32>> { o[k].as_array()?.iter().map(|x| x.as_f64().map(|v| v as f32)).collect() };
    let (p, q, s) = (f("world_position")?, f("world_rotation")?, f("world_scale")?);
    Some(Mat4::from_scale_rotation_translation(
        Vec3::new(s[0], s[1], s[2]),
        Quat::from_xyzw(-q[0], -q[1], q[2], q[3]),
        Vec3::new(p[0], p[1], -p[2]),
    ))
}

fn is_hull_slice(mesh: &str) -> bool {
    let rest = mesh.strip_prefix("Dorm_").unwrap_or("");
    rest.starts_with(|c: char| c.is_ascii_digit()) || rest.starts_with("Trim") || rest.starts_with("Mezzanine")
}

/// Prefabs whose 2026 mesh was replaced: the prefab's root goes where this scene object is.
const ANCHORS: [(&str, &str); 5] = [
    ("(Dorm_FreeMirror)", "Enviroment/Static/[DormRoom2Env]/DormRoom2_fbx/MirrorHolder/Quad"),
    ("(Dorm_Mirror_Buttons)", "Enviroment/Static/[MirrorUIRoot]/Canvas/RRUIRoot/MirrorButtons"),
    ("(Dorm_Fluorescent_Light)", "Enviroment/Static/[Light_Fluorescent]"),
    ("(Dorm_Community_Board)", "(DormRoom2Systems)/MessageBoard"),
    ("(Dorm_Help_Buttons)", "(DormRoom2Systems)/[HelpButtonsCanvas]"),
];

/// Meshes shared by many unrelated objects: a match on them says nothing about where a prefab goes.
const GENERIC: [&str; 4] = ["ButtonRectangle", "LOD0", "LOD1", "LOD2"];

fn main() {
    let mut args = std::env::args().skip(1);
    let scene_path = args.next().expect("usage: dorm_layout_gen <scene.json> [game dir]");
    let game = args.next().map(std::path::PathBuf::from)
        .or_else(|| room::GAME_DIRS.iter().map(std::path::PathBuf::from).find(|p| p.exists()))
        .expect("no game folder");
    let scene: Vec<serde_json::Value> = serde_json::from_str(&std::fs::read_to_string(&scene_path).unwrap()).unwrap();
    let active = |o: &&serde_json::Value| o["active_in_hierarchy"].as_bool() == Some(true);
    let hull = scene.iter().find(|o| o["path"].as_str().is_some_and(|p| p.ends_with("/DormRoom2_fbx")))
        .and_then(unity_world).expect("no DormRoom2_fbx in the scene");

    let dir = room::bundle_dir(&game);
    let mut lib = Library::new(&dir).unwrap();
    let kit = room::load_prefabs(&mut lib, &dir, "43ea1176ca25c0333547813ec3298808.bundle", |n| n.starts_with("(Dorm_"), &[]).unwrap();

    println!("# Generated by examples/dorm_layout_gen.rs from the original Dorm scene (dormroom2); x y z qx qy qz qw sx sy sz");
    let mut unmatched = Vec::new();
    for (i, name) in kit.roots.iter().enumerate() {
        if let Some((_, path)) = ANCHORS.iter().find(|(n, _)| n == name) {
            let Some(w) = scene.iter().find(|o| o["path"].as_str() == Some(*path)).and_then(unity_world) else {
                unmatched.push(name.clone());
                continue;
            };
            let (s, r, t) = w.to_scale_rotation_translation();
            println!("{name:30} {:8.4} {:8.4} {:8.4}  {:8.5} {:8.5} {:8.5} {:8.5}  {:6.4} {:6.4} {:6.4}   # at {path}",
                t.x, t.y, t.z, r.x, r.y, r.z, r.w, s.x, s.y, s.z);
            continue;
        }
        let found = kit.parts.iter().filter(|p| p.root == i).find_map(|p| {
            if is_hull_slice(&p.mesh) {
                return Some((p, hull, "hull".to_string()));
            }
            let want = p.mesh.as_str();
            if GENERIC.contains(&want) {
                return None;
            }
            // an active copy if there is one; some props (the bulletin board) are switched off in the scene
            let same = |o: &&serde_json::Value| o["mesh"].as_str() == Some(want);
            let o = scene.iter().filter(active).find(same).or_else(|| scene.iter().find(same))?;
            Some((p, unity_world(o)?, o["path"].as_str().unwrap_or("").to_string()))
        });
        let Some((part, w, from)) = found else {
            unmatched.push(name.clone());
            continue;
        };
        let (s, r, t) = (w * part.world.inverse()).to_scale_rotation_translation();
        println!("{name:30} {:8.4} {:8.4} {:8.4}  {:8.5} {:8.5} {:8.5} {:8.5}  {:6.4} {:6.4} {:6.4}   # {} <- {from}",
            t.x, t.y, t.z, r.x, r.y, r.z, r.w, s.x, s.y, s.z, part.mesh);
    }
    for n in unmatched {
        println!("# not in the original scene: {n}");
    }
}
